const assert = require("node:assert/strict");
const fs = require("node:fs");
const { chromium } = require("playwright");
const url = process.argv[2] || "http://127.0.0.1:8992/index.html";
const output = process.argv[3] || "reports/g18c/captures";
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  fs.mkdirSync(output,{recursive:true});
  const browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||"/usr/bin/chromium",args:["--no-sandbox","--use-gl=angle","--use-angle=swiftshader","--enable-webgl","--disable-dev-shm-usage"]});
  const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  page.on("console",m=>{if(m.type()==="error")errors.push(m.text());});
  page.on("requestfailed",r=>errors.push(`${r.url()} ${r.failure()?.errorText||""}`));
  await page.goto(url,{waitUntil:"domcontentloaded",timeout:60000});
  await page.waitForFunction(()=>document.querySelector("canvas"),null,{timeout:60000});
  await sleep(4500);
  await page.mouse.click(343,804); await sleep(1500);
  await page.mouse.click(300,92); await sleep(300);
  const [download]=await Promise.all([page.waitForEvent("download"),page.mouse.click(100,194)]);
  const savedPath="/tmp/g18c-cascudo-save.json"; await download.saveAs(savedPath);
  const parsed=JSON.parse(fs.readFileSync(savedPath,"utf8"));
  parsed.payload.map_id="MAP_02"; parsed.payload.cell={x:6,y:3};
  const chooserPromise=page.waitForEvent("filechooser");
  const picker=await page.evaluate(()=>document.getElementById("sotomar-save-import").getBoundingClientRect().toJSON());
  await page.mouse.click(picker.x+picker.width/2,picker.y+picker.height/2);
  await (await chooserPromise).setFiles({name:"g18c-cascudo-test.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(parsed))});
  await sleep(800); await page.mouse.click(300,525); await sleep(5500);
  await page.mouse.click(300,92); await sleep(500); await page.mouse.click(180,800); await sleep(4500);
  await page.screenshot({path:`${output}/combat-cascudo-de-cal-390x844.png`});
  const state=await page.evaluate(()=>({canvas:!!document.querySelector("canvas"),title:document.title}));
  fs.writeFileSync(`${output}/combat-cascudo-check.json`,JSON.stringify({url,state,errors,expected:"ENC_01 Cascudo-de-cal test presentation; reserved placement remains provisional"},null,2)+"\n");
  assert.equal(state.canvas,true); assert.deepEqual(errors,[]);
  console.log("PASS: Chromium loaded the Godot Web export and captured the provisional ENC_01 Cascudo encounter without runtime errors");
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
