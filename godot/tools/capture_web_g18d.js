const assert = require("node:assert/strict");
const fs = require("node:fs");
const { chromium } = require("playwright");

const url = process.argv[2] || "http://127.0.0.1:8992/index.html";
const output = process.argv[3] || "reports/g18d/captures";
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-webgl", "--disable-dev-shm-usage"] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  page.on("requestfailed", (request) => errors.push(`${request.url()} ${request.failure()?.errorText || ""}`));
  await page.goto(url, { waitUntil: "domcontentloaded", timeout: 30000 });
  await page.waitForFunction(() => document.querySelector("canvas"), null, { timeout: 30000 });
  await sleep(4500);
  await page.mouse.click(343, 804);
  await sleep(3000);
  await page.mouse.click(300, 92);
  await sleep(300);
  const [download] = await Promise.all([page.waitForEvent("download"), page.mouse.click(100, 194)]);
  const savedPath = `/tmp/${download.suggestedFilename()}`;
  await download.saveAs(savedPath);
  const parsed = JSON.parse(fs.readFileSync(savedPath, "utf8"));
  parsed.payload.map_id = "MAP_04";
  parsed.payload.cell = { x: 6, y: 1 };
  const chooserPromise = page.waitForEvent("filechooser");
  const picker = await page.evaluate(() => document.getElementById("sotomar-save-import").getBoundingClientRect().toJSON());
  await page.mouse.click(picker.x + picker.width / 2, picker.y + picker.height / 2);
  await (await chooserPromise).setFiles({ name: "g18b-combat-start.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(parsed)) });
  await sleep(800);
  await page.screenshot({ path: `${output}/mobile-import-preview.png` });
  await page.mouse.click(300, 525);
  await sleep(6500);
  await page.screenshot({ path: `${output}/mobile-imported-map04.png` });
  await page.mouse.click(300, 92);
  await sleep(500);
  await page.mouse.click(180, 800);
  await sleep(3000);
  await page.screenshot({ path: `${output}/mobile-combat.png` });
  const viewports = [[360,800,"360x800"],[390,844,"390x844"],[844,390,"844x390"],[1280,720,"1280x720"]];
  for (const [width,height,label] of viewports) {
    await page.setViewportSize({width,height});
    await sleep(600);
    await page.screenshot({path:`${output}/combat-enc05-${label}.png`});
  }
  await page.setViewportSize({width:390,height:844});
  await page.mouse.click(45, 798);
  await sleep(400);
  await page.mouse.click(159, 519);
  await sleep(400);
  await page.mouse.click(70, 826);
  await sleep(400);
  await page.screenshot({ path: `${output}/mobile-lanca-selected.png` });
  await page.mouse.click(195, 537);
  await sleep(900);
  await page.screenshot({ path: `${output}/mobile-lanca-target-result.png` });
  await page.mouse.click(70, 826);
  await sleep(300);
  await page.mouse.click(195, 537);
  await sleep(900);
  await page.mouse.click(228, 826);
  await sleep(3500);
  await page.screenshot({ path: `${output}/mobile-enemy-turn.png` });
  await page.mouse.click(100, 798);
  await sleep(300);
  await page.mouse.click(177, 528);
  await sleep(1800);
  await page.screenshot({ path: `${output}/mobile-after-golpe.png` });
  const state = await page.evaluate(() => ({ canvas: !!document.querySelector("canvas"), title: document.title }));
  fs.writeFileSync(`${output}/combat-browser-check.json`, JSON.stringify({ url, state, errors, viewports:viewports.map(([w,h])=>[w,h]), encounter:"ENC_05 Topetão", validation:"Chromium Web render; screenshots captured during combat; no physical device claim" }, null, 2) + "\n");
  assert.equal(state.canvas, true);
  assert.deepEqual(errors, [], `browser errors: ${errors.join(" | ")}`);
  console.log("PASS: Web runtime loaded, ENC_05 opened and Lança/Golpe combat inputs were exercised at four viewport sizes without browser console/network errors");
  await browser.close();
})().catch((error) => { console.error(error); process.exitCode = 1; });
